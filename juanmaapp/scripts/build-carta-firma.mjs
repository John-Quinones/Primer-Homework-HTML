// Version 2.3.9: writes public/carta-firma-tpl.js, the letter of «Firmar y enviar por correo» (src/plantillas/carta-firma-correo.html)
// with the letterhead pictures inside as data URIs, so the page and the single-file link carry it without extra requests.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const img = (f) => "data:image/png;base64," + readFileSync(path.join(root, "public", f)).toString("base64");
const html = readFileSync(path.join(root, "src/plantillas/carta-firma-correo.html"), "utf8").replace("<!--tj-html-->\n", "")
  .replaceAll("@@LOGO@@", () => img("carta-logo.png")).replaceAll("@@HQR@@", () => img("carta-qr.png"))
  .replaceAll("@@GLOBE@@", () => img("carta-globo.png")).replaceAll("@@LOC@@", () => img("carta-ubicacion.png"));
writeFileSync(path.join(root, "public/carta-firma-tpl.js"), `// Generated by scripts/build-carta-firma.mjs from src/plantillas/carta-firma-correo.html. Do not edit by hand.\nwindow.JuanmaCartaTpl = ${JSON.stringify(html)};\n`);
console.log("Wrote public/carta-firma-tpl.js");
